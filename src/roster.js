export function allStudents() {
  return Object.values(COURSE_GROUPS).flatMap(group =>
    group.students.map(student => ({...student, groupId: group.id, groupLabel: group.label}))
  );
}

export function findStudentByEmail(email='') {
  const needle=String(email).trim().toLowerCase();
  return allStudents().find(student => student.email === needle) || null;
}

export function getGroup(groupId='') {
  return COURSE_GROUPS[String(groupId).trim()] || null;
}
